#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_named_group_names() {
        assert_eq!(NamedGroup::SECP256R1.name(), "secp256r1");
        assert_eq!(NamedGroup::X25519.name(), "x25519");
        assert_eq!(NamedGroup::FFDHE2048.name(), "ffdhe2048");
    }

    #[test]
    fn test_group_classification() {
        assert!(NamedGroup::SECP256R1.is_ecdh());
        assert!(NamedGroup::X25519.is_ecdh());
        assert!(!NamedGroup::SECP256R1.is_ffdh());

        assert!(NamedGroup::FFDHE2048.is_ffdh());
        assert!(!NamedGroup::FFDHE2048.is_ecdh());

        assert!(NamedGroup::X25519_MLKEM768.is_post_quantum());
    }

    #[test]
    fn test_key_share_len() {
        assert_eq!(NamedGroup::SECP256R1.key_share_len(), Some(65));
        assert_eq!(NamedGroup::X25519.key_share_len(), Some(32));
        assert_eq!(NamedGroup::FFDHE2048.key_share_len(), None);
    }

    #[test]
    fn test_ffdhe2048_prime() {
        assert_eq!(FFDHE2048.prime.len(), 256); // 2048 bits = 256 bytes
        assert_eq!(FFDHE2048.generator, 2);
    }
}
