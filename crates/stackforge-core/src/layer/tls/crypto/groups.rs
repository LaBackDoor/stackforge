//! TLS Named Groups (key exchange groups).
//!
//! Defines elliptic curve and finite-field DH groups used in TLS.

/// Named group identifiers from the TLS registry.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct NamedGroup(pub u16);

impl NamedGroup {
    // Elliptic curve groups
    pub const SECP256R1: Self = Self(0x0017);
    pub const SECP384R1: Self = Self(0x0018);
    pub const SECP521R1: Self = Self(0x0019);
    pub const X25519: Self = Self(0x001D);
    pub const X448: Self = Self(0x001E);

    // Finite field DH groups (RFC 7919)
    pub const FFDHE2048: Self = Self(0x0100);
    pub const FFDHE3072: Self = Self(0x0101);
    pub const FFDHE4096: Self = Self(0x0102);
    pub const FFDHE6144: Self = Self(0x0103);
    pub const FFDHE8192: Self = Self(0x0104);

    // Post-quantum hybrid groups
    pub const SECP256R1_MLKEM768: Self = Self(0x11EB);
    pub const X25519_MLKEM768: Self = Self(0x11EC);
    pub const X25519_KYBER768_DRAFT00: Self = Self(0x6399);

    /// Get the human-readable name.
    pub fn name(&self) -> &'static str {
        match self.0 {
            0x0017 => "secp256r1",
            0x0018 => "secp384r1",
            0x0019 => "secp521r1",
            0x001D => "x25519",
            0x001E => "x448",
            0x0100 => "ffdhe2048",
            0x0101 => "ffdhe3072",
            0x0102 => "ffdhe4096",
            0x0103 => "ffdhe6144",
            0x0104 => "ffdhe8192",
            0x11EB => "SecP256r1MLKEM768",
            0x11EC => "X25519MLKEM768",
            0x6399 => "X25519Kyber768Draft00",
            _ => "unknown",
        }
    }

    /// Check if this is an elliptic curve group.
    pub fn is_ecdh(&self) -> bool {
        matches!(self.0, 0x0017..=0x001E)
    }

    /// Check if this is a finite-field DH group.
    pub fn is_ffdh(&self) -> bool {
        matches!(self.0, 0x0100..=0x0104)
    }

    /// Check if this is a post-quantum hybrid group.
    pub fn is_post_quantum(&self) -> bool {
        matches!(self.0, 0x11EB | 0x11EC | 0x6399)
    }

    /// Get the key share length for this group.
    pub fn key_share_len(&self) -> Option<usize> {
        match self.0 {
            0x0017 => Some(65),  // secp256r1 uncompressed point
            0x0018 => Some(97),  // secp384r1
            0x0019 => Some(133), // secp521r1
            0x001D => Some(32),  // x25519
            0x001E => Some(56),  // x448
            _ => None,
        }
    }
}

